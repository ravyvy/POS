// CRC-16/CCITT-FALSE — the checksum algorithm EMVCo QR (and therefore
// Bakong KHQR) uses for tag 63. Poly 0x1021, init 0xFFFF, no reflection.
function crc16(str) {
  let crc = 0xffff;
  for (let i = 0; i < str.length; i++) {
    crc ^= str.charCodeAt(i) << 8;
    for (let j = 0; j < 8; j++) {
      if ((crc & 0x8000) !== 0) {
        crc = ((crc << 1) ^ 0x1021) & 0xffff;
      } else {
        crc = (crc << 1) & 0xffff;
      }
    }
  }
  return crc.toString(16).toUpperCase().padStart(4, "0");
}

module.exports = { crc16 };